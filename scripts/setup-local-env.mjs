// Reads `supabase status` and writes a local .env.local for development + e2e.
// The keys printed by local Supabase are well-known demo keys (identical on
// every machine), so this file is safe to (re)generate but is gitignored.
import { execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

function readStatusEnv() {
  let out
  try {
    out = execSync('supabase status -o env', { encoding: 'utf8' })
  } catch {
    console.error('❌ Could not run `supabase status`. Start it first: npm run db:start')
    process.exit(1)
  }
  const env = {}
  for (const line of out.split('\n')) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/)
    if (!m) continue
    let value = m[2].trim()
    if (value.startsWith('"') && value.endsWith('"')) value = value.slice(1, -1)
    env[m[1]] = value
  }
  return env
}

const status = readStatusEnv()
const apiUrl = status.API_URL || 'http://127.0.0.1:54321'
const anonKey = status.ANON_KEY
const serviceKey = status.SERVICE_ROLE_KEY

if (!anonKey || !serviceKey) {
  console.error('❌ Missing ANON_KEY / SERVICE_ROLE_KEY. Is Supabase running? (npm run db:start)')
  process.exit(1)
}

const content = `# Auto-generated by \`npm run env:local\` — DO NOT COMMIT.
VITE_SUPABASE_URL=${apiUrl}
VITE_SUPABASE_ANON_KEY=${anonKey}
SUPABASE_URL=${apiUrl}
SUPABASE_SERVICE_ROLE_KEY=${serviceKey}
`

writeFileSync(new URL('../.env.local', import.meta.url), content)
console.log('✅ Wrote .env.local pointing at local Supabase:', apiUrl)
